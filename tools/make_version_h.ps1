# Writes build\wren_version.h from APP_VERSION (src\browser\about.odin): the numbers the version resource of wren.exe
# (src\browser\wren.rc, wren_dev.rc) puts in the file. Run by build.bat before it compiles, so the executable's File
# version is never a second copy of the version to edit by hand. The file is rewritten only when its content changes,
# to leave the resource (and so the link) alone on a build that changes nothing.
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$m = Select-String -Path (Join-Path $root 'src\browser\about.odin') -Pattern 'APP_VERSION\s*::\s*"(\d+)\.(\d+)\.(\d+)"'
if (-not $m) { throw 'APP_VERSION (major.minor.patch) not found in src\browser\about.odin' }
$g = $m.Matches[0].Groups
$text = @"
// Generated by tools\make_version_h.ps1 from APP_VERSION (src/browser/about.odin): do not edit.
#define WREN_VER_MAJOR $($g[1].Value)
#define WREN_VER_MINOR $($g[2].Value)
#define WREN_VER_PATCH $($g[3].Value)
#define WREN_VER_STRING "$($g[1].Value).$($g[2].Value).$($g[3].Value)"

"@ -replace "`r?`n", "`r`n"
$dir = Join-Path $root 'build'
New-Item -ItemType Directory -Force $dir | Out-Null
$path = Join-Path $dir 'wren_version.h'
if (-not (Test-Path $path) -or [IO.File]::ReadAllText($path) -ne $text) {
    [IO.File]::WriteAllText($path, $text, (New-Object Text.UTF8Encoding $false))
}
