// The 2D canvas: context, state, paths, styles, pixels (ImageData), Path2D, DOMMatrix, OffscreenCanvas, ImageBitmap,
// encoding. Nothing is painted in this tool (no shell): drawings are read back with getImageData.

const px = (ctx, x, y) => Array.from(ctx.getImageData(x, y, 1, 1).data);
const mk = (w = 40, h = 30) => { const c = document.createElement("canvas"); c.width = w; c.height = h; return [c, c.getContext("2d")]; };

test("the element", () => {
  const c = document.createElement("canvas");
  eq(c.width, 300, "default width");
  eq(c.height, 150, "default height");
  c.width = 20; c.height = 10;
  eq(c.getAttribute("width"), "20", "width is the attribute");
  c.setAttribute("width", "  33abc");
  eq(c.width, 33, "attribute parsed as HTML parses integers");
  c.setAttribute("height", "-5");
  eq(c.height, 150, "negative: the default");
  c.width = 0;
  eq(c.width, 0, "zero is allowed");
  ok(c instanceof HTMLCanvasElement, "an HTMLCanvasElement");
  eq(c.getContext("webgl"), null, "no webgl");
  eq(c.getContext("bitmaprenderer"), null, "no bitmaprenderer");
  const g = c.getContext("2d");
  ok(g instanceof CanvasRenderingContext2D, "a CanvasRenderingContext2D");
  eq(c.getContext("2d"), g, "the same context every time");
  eq(g.canvas, c, "context.canvas");
  throws(() => c.getContext(), "TypeError", "getContext needs an argument");
  eq(Object.prototype.toString.call(g), "[object CanvasRenderingContext2D]", "toStringTag");
});

