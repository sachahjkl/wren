test("ImageData", () => {
  const d = new ImageData(3, 2);
  eq(d.width, 3, "width");
  eq(d.height, 2, "height");
  ok(d.data instanceof Uint8ClampedArray, "a Uint8ClampedArray");
  eq(d.data.length, 24, "4 bytes a pixel");
  eq(d.colorSpace, "srgb", "colorSpace");
  eq(d.data, d.data, "data is the same object");
  const own = new Uint8ClampedArray(16);
  const e = new ImageData(own, 2);
  eq(e.height, 2, "the height from the data");
  eq(e.data, own, "the data is the one given");
  throws(() => new ImageData(0, 5), "IndexSizeError", "zero width");
  throws(() => new ImageData(new Uint8ClampedArray(5), 1), "InvalidStateError", "data not a multiple of 4");
  throws(() => new ImageData(new Uint8ClampedArray(16), 3), "InvalidStateError", "data not a multiple of the width");
  throws(() => new ImageData(new Uint8Array(16), 2), "TypeError", "not clamped");
  throws(() => ImageData(1, 1), "TypeError", "needs new");
  const [c, g] = mk(8, 8);
  const cd = g.createImageData(2, 2);
  eq(cd.data.every((v) => v === 0), true, "createImageData is transparent");
  const twin = g.createImageData(cd);
  eq(twin.width + "x" + twin.height, "2x2", "createImageData(imageData) copies the size");
  throws(() => g.createImageData(0, 1), "IndexSizeError", "zero size");
  cd.data.set([10, 20, 30, 255, 40, 50, 60, 128, 0, 0, 0, 0, 255, 255, 255, 255]);
  g.putImageData(cd, 1, 1);
  eq(px(g, 1, 1).join(), "10,20,30,255", "putImageData / getImageData");
  const back = px(g, 2, 1);
  ok(Math.abs(back[0] - 40) <= 1 && back[3] === 128, "a translucent pixel survives within rounding");
  g.putImageData(cd, 4, 4, 1, 1, 1, 1);
  eq(px(g, 5, 5).join(), "255,255,255,255", "putImageData with a dirty rectangle");
  eq(px(g, 4, 4).join(), "0,0,0,0", "...touches nothing else");
  const edge = g.getImageData(-1, -1, 3, 3);
  eq(edge.data[3], 0, "outside the canvas is transparent");
  eq(Array.from(edge.data.slice(32, 36)).join(), "10,20,30,255", "...and inside it is the pixel");
  throws(() => g.getImageData(0, 0, 0, 5), "IndexSizeError", "an empty source");
  g.save();
  g.rect(0, 0, 1, 1);
  g.clip();
  g.putImageData(cd, 3, 3);
  g.restore();
  eq(px(g, 3, 3).join(), "10,20,30,255", "putImageData ignores the clip");
  const neg = g.getImageData(3, 3, -2, -2);
  eq(neg.width, 2, "negative sizes flip the rectangle");
});

