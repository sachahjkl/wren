  g.beginPath();
  g.rect(0, 0, 10, 10);
  g.rect(2, 2, 6, 6);
  ok(g.isPointInPath(5, 5, "nonzero") && !g.isPointInPath(5, 5, "evenodd"), "isPointInPath with a fill rule");
  throws(() => g.arc(0, 0, -1, 0, 1), "IndexSizeError", "a negative radius");
  throws(() => g.ellipse(0, 0, 1, -1, 0, 0, 1), "IndexSizeError", "a negative ellipse radius");
  throws(() => g.arcTo(0, 0, 1, 1, -5), "IndexSizeError", "arcTo with a negative radius");
