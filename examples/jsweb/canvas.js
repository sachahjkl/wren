test("clip, shadows, filters", () => {
  const [c, g] = mk(40, 40);
  g.beginPath();
  g.rect(10, 10, 10, 10);
  g.clip();
  g.fillStyle = "red";
  g.fillRect(0, 0, 40, 40);
  eq(px(g, 15, 15)[3], 255, "inside the clip");
  eq(px(g, 5, 5)[3], 0, "outside the clip");
  g.reset();
  g.shadowColor = "black";
  g.shadowOffsetX = 10;
  g.shadowOffsetY = 10;
  g.fillStyle = "red";
  g.fillRect(5, 5, 10, 10);
  eq(px(g, 17, 17).join(), "0,0,0,255", "a shadow");
  eq(g.shadowColor, "#000000", "shadowColor reads back");
  g.clearRect(0, 0, 40, 40);
  g.shadowOffsetX = g.shadowOffsetY = 0;
  g.shadowBlur = 6;
  g.fillRect(15, 15, 10, 10);
  const halo = px(g, 12, 20)[3];
  ok(halo > 5 && halo < 255, "a blurred shadow spreads: " + halo);
  g.shadowBlur = -1;
  eq(g.shadowBlur, 6, "a negative blur is ignored");
  g.reset();
  eq(g.filter, "none", "no filter");
  g.filter = "blur(2px) brightness(120%)";
  eq(g.filter, "blur(2px) brightness(120%)", "filter reads back");
  g.filter = "grayscale(1)";
  g.fillStyle = "#f00";
  g.fillRect(10, 10, 10, 10);
  const grey = px(g, 15, 15);
  ok(Math.abs(grey[0] - grey[1]) < 3 && Math.abs(grey[1] - grey[2]) < 3 && grey[0] > 40, "grayscale: " + grey);
  g.filter = "bogus(3)";
  eq(g.filter, "grayscale(1)", "an invalid filter is ignored");
});

test("encoding", async () => {
  const [c, g] = mk(8, 8);
  g.fillStyle = "#336699";
  g.fillRect(0, 0, 8, 8);
  const url = c.toDataURL();
  ok(url.startsWith("data:image/png;base64,"), "toDataURL gives a PNG: " + url.slice(0, 30));
  const png = Uint8Array.from(atob(url.slice(22)), (ch) => ch.charCodeAt(0));
  eq(Array.from(png.slice(0, 8)).join(), "137,80,78,71,13,10,26,10", "PNG signature");
  ok(c.toDataURL("image/jpeg", 0.8).startsWith("data:image/jpeg;base64,"), "JPEG");
  ok(c.toDataURL("image/webp").startsWith("data:image/png"), "an unsupported type falls back to PNG");
  const empty = document.createElement("canvas");
  empty.width = 0;
  eq(empty.toDataURL(), "data:,", "an empty canvas");
  const blob = await new Promise((r) => c.toBlob(r));
  ok(blob instanceof Blob && blob.type === "image/png" && blob.size > 20, "toBlob");
  const jpg = await new Promise((r) => c.toBlob(r, "image/jpeg", 0.5));
  eq(jpg.type, "image/jpeg", "toBlob JPEG");
  const o = new OffscreenCanvas(4, 4);
  o.getContext("2d").fillRect(0, 0, 4, 4);
  const ob = await o.convertToBlob();
  eq(ob.type, "image/png", "convertToBlob");
  throws(() => c.toBlob(), "TypeError", "toBlob needs a callback");
});

test("limits and hostile input", () => {
  const c = document.createElement("canvas");
  c.width = 100000;
  c.height = 100000;
  const g = c.getContext("2d");
  g.fillRect(0, 0, 10, 10);
  g.getImageData(0, 0, 1, 1).data;
  eq(c.width, 100000, "an absurd size is kept as the attribute says");
  const d = document.createElement("canvas");
  d.width = 10; d.height = 10;
  const h = d.getContext("2d");
  for (let k = 0; k < 20000; k++) h.save();
  for (let k = 0; k < 20000; k++) h.restore();
  h.scale(1e308, 1e308);
  h.scale(1e308, 1e308);
  h.fillRect(0, 0, 1e308, 1e308);
  h.setTransform(0, 0, 0, 0, 0, 0);
  h.fillRect(0, 0, 5, 5);
  h.stroke();
  h.setLineDash([1e-9, 1e-9]);
  h.lineWidth = 1e308;
  h.beginPath(); h.moveTo(0, 0); h.lineTo(1e300, 1e300); h.stroke();
  h.shadowBlur = 1e9; h.shadowColor = "black"; h.shadowOffsetX = 1;
  h.fillRect(0, 0, 3, 3);
  ok(true, "survived");
  d.width = d.width;
  ok(h.getTransform().isIdentity, "assigning width resets the context");
  eq(px(h, 0, 0).join(), "0,0,0,0", "...and clears");
  const opaque = document.createElement("canvas");
  opaque.width = 4; opaque.height = 4;
  const og = opaque.getContext("2d", { alpha: false });
  eq(px(og, 0, 0).join(), "0,0,0,255", "alpha: false starts opaque black");
  og.clearRect(0, 0, 4, 4);
  eq(px(og, 0, 0)[3], 255, "...and stays opaque");
  eq(og.getContextAttributes().alpha, false, "getContextAttributes");
});

