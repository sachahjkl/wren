  g.rect(20, 20, 20, 20);
  g.fill("evenodd");
  eq(px(g, 30, 30)[3], 0, "evenodd leaves a hole");
  eq(px(g, 12, 12)[3], 255, "...around it");
  g.clearRect(0, 0, 60, 60);
  g.beginPath();
  g.moveTo(10, 10);
  g.lineTo(50, 10);
  g.lineTo(50, 50);
  g.closePath();
  g.fill();
  eq(px(g, 40, 20)[3], 255, "a closed triangle");
  eq(px(g, 15, 40)[3], 0, "...and not the other half");
