test("state: save, restore, transform", () => {
  const [c, g] = mk();
  g.fillStyle = "#00ff00";
  g.globalAlpha = 0.5;
  g.save();
  g.fillStyle = "#0000ff";
  g.globalAlpha = 1;
  g.translate(10, 10);
  g.restore();
  eq(g.fillStyle, "#00ff00", "fillStyle restored");
  eq(g.globalAlpha, 0.5, "globalAlpha restored");
  const m = g.getTransform();
  ok(m instanceof DOMMatrix && m.isIdentity, "identity transform restored");
  g.setTransform(2, 0, 0, 2, 5, 6);
  const t = g.getTransform();
  eq([t.a, t.b, t.c, t.d, t.e, t.f].join(), "2,0,0,2,5,6", "setTransform / getTransform");
  g.setTransform(new DOMMatrix([1, 0, 0, 1, 3, 4]));
  eq(g.getTransform().e, 3, "setTransform(DOMMatrix)");
  g.setTransform({ a: 1, b: 0, c: 0, d: 1, e: 7, f: 8 });
  eq(g.getTransform().f, 8, "setTransform(dictionary)");
  g.resetTransform();
  ok(g.getTransform().isIdentity, "resetTransform");
  g.rotate(Math.PI / 2);
  g.translate(1, 0);
  const r = g.getTransform();
  ok(Math.abs(r.b - 1) < 1e-12 && Math.abs(r.f - 1) < 1e-12, "rotate then translate");
  g.rotate(NaN);
  ok(Math.abs(g.getTransform().b - 1) < 1e-12, "a NaN angle changes nothing");
  g.reset();
  ok(g.getTransform().isIdentity && g.globalAlpha === 1, "reset() puts the defaults back");
  throws(() => g.setTransform(1, 2, 3), "TypeError", "setTransform with three numbers");
});

