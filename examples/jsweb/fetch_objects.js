// Headers, Request, Response without the network; FormData.

test("Headers", () => {
  const h = new Headers({ "Content-Type": "text/plain", "X-A": " 1 " });
  eq(h.get("content-type"), "text/plain", "case-insensitive get");
  eq(h.get("x-a"), "1", "values are trimmed");
  h.append("x-a", "2");
  eq(h.get("X-A"), "1, 2", "combined values");
  eq(h.has("x-b"), false, "has");
  h.set("x-a", "3");
  eq(h.get("x-a"), "3", "set replaces");
  h.delete("content-type");
  eq(h.get("content-type"), null, "delete");
  h.append("b-z", "z");
  h.append("Set-Cookie", "a=1");
  h.append("set-cookie", "b=2");
  eq(show([...h]), '[["b-z","z"],["set-cookie","a=1"],["set-cookie","b=2"],["x-a","3"]]', "iteration: sorted, lower case, set-cookie apart");
  eq(show(h.getSetCookie()), '["a=1","b=2"]', "getSetCookie");
  eq([...h.keys()].join(), "b-z,set-cookie,set-cookie,x-a", "keys");
  throws(() => h.append("bad name", "x"), "TypeError", "invalid name");
  throws(() => h.append("x", "a\nb"), "TypeError", "invalid value");
  throws(() => h.get("\u0100"), "TypeError", "ByteString");
  eq(new Headers([["a", "1"], ["a", "2"]]).get("a"), "1, 2", "from pairs");
  eq(new Headers(new Headers({ q: "r" })).get("q"), "r", "from a Headers");
  throws(() => new Headers([["a"]]), "TypeError", "a pair of one");
  let n = 0;
  new Headers({ a: "1", b: "2" }).forEach((v, k) => { n += k.length + v.length; });
  eq(n, 4, "forEach");
});

test("Request", async () => {
  const r = new Request("/jsweb/json?x", { method: "post", headers: { "X-T": "1", Cookie: "c=1", "Sec-Foo": "no" }, body: "hello" });
  eq(r.url, "http://127.0.0.1:8765/jsweb/json?x", "URL resolved against the document");
  eq(r.method, "POST", "method normalized");
  eq(r.headers.get("x-t"), "1", "headers");
  eq(r.headers.get("cookie"), null, "a forbidden request header is dropped");
  eq(r.headers.get("sec-foo"), null, "Sec- headers are dropped");
  eq(r.headers.get("content-type"), "text/plain;charset=UTF-8", "the body's Content-Type");
  eq(r.mode, "cors", "mode");
  eq(r.credentials, "same-origin", "credentials");
  eq(r.redirect, "follow", "redirect");
  eq(r.cache, "default", "cache");
  eq(r.referrer, "about:client", "referrer");
  eq(r.destination, "", "destination");
  ok(r.signal instanceof AbortSignal, "signal");
  eq(r.bodyUsed, false, "bodyUsed");
  const c = r.clone();
  eq(await r.text(), "hello", "text()");
  eq(r.bodyUsed, true, "bodyUsed after");
  await rejects(r.text(), "TypeError", "a body is read once");
  eq(await c.text(), "hello", "the clone has its own body");
  throws(() => new Request("/x", { method: "GET", body: "b" }), "TypeError", "GET with a body");
  throws(() => new Request("/x", { method: "TRACE" }), "TypeError", "forbidden method");
  throws(() => new Request("/x", { mode: "navigate" }), "TypeError", "mode navigate");
  throws(() => new Request("http://u:p@h/"), "TypeError", "credentials in the URL");
  throws(() => new Request("/x", { headers: { "a b": "c" } }), "TypeError", "invalid header");
  const nc = new Request("/x", { mode: "no-cors", headers: { "X-Custom": "1", "Accept": "a/b" } });
  eq(nc.headers.get("x-custom"), null, "no-cors: only safelisted headers");
  eq(nc.headers.get("accept"), "a/b", "no-cors: Accept kept");
  const ac = new AbortController();
  const rs = new Request("/x", { signal: ac.signal });
  ac.abort("stop");
  eq(rs.signal.aborted, true, "the request's signal follows the given one");
  eq(rs.signal.reason, "stop", "with its reason");
  const copy = new Request(new Request("/y", { method: "PUT", body: "z" }));
  eq(copy.method, "PUT", "from another Request");
  eq(await copy.text(), "z", "its body moves");
  eq(await new Request("/x", { method: "POST", body: new Uint8Array([104, 105]) }).text(), "hi", "BufferSource body");
});

test("Response", async () => {
  const r = new Response("body", { status: 201, statusText: "Made", headers: { "X-Y": "z" } });
  eq(r.status, 201, "status");
  eq(r.ok, true, "ok");
  eq(r.statusText, "Made", "statusText");
  eq(r.type, "default", "type");
  eq(r.url, "", "url");
  eq(r.headers.get("x-y"), "z", "headers");
  eq(r.headers.get("content-type"), "text/plain;charset=UTF-8", "Content-Type from the body");
  eq(await r.text(), "body", "text()");
  throws(() => new Response("", { status: 99 }), "RangeError", "status out of range");
  throws(() => new Response("x", { status: 204 }), "TypeError", "null body status with a body");
  throws(() => new Response("", { statusText: "a\nb" }), "TypeError", "bad statusText");
  eq(new Response(null, { status: 204 }).body, null, "a null body");
  const e = Response.error();
  eq(e.type, "error", "error()");
  eq(e.status, 0, "error status");
  throws(() => e.headers.set("a", "b"), "TypeError", "immutable headers");
  const rd = Response.redirect("/target", 301);
  eq(rd.status, 301, "redirect status");
  eq(rd.headers.get("location"), "http://127.0.0.1:8765/target", "redirect Location resolved");
  throws(() => Response.redirect("/t", 200), "RangeError", "redirect with a non-redirect status");
  const j = Response.json({ a: [1] }, { status: 202 });
  eq(j.headers.get("content-type"), "application/json", "json() type");
  eq((await j.json()).a[0], 1, "json() body");
  throws(() => Response.json(undefined), "TypeError", "json() of undefined");
  eq(new Uint8Array(await new Response(new Uint8Array([1, 2, 3])).arrayBuffer())[2], 3, "arrayBuffer()");
  const bl = await new Response("abc", { headers: { "Content-Type": "Text/X" } }).blob();
  eq(bl.size + bl.type, "3text/x", "blob()");
  await rejects(new Response("{").json(), "SyntaxError", "json() of invalid JSON");
  const st = new Response("streamed").body;
  ok(st instanceof ReadableStream, "body is a ReadableStream");
  const { value } = await st.getReader().read();
  eq(new TextDecoder().decode(value), "streamed", "a Uint8Array chunk");
  const fromStream = new Response(new ReadableStream({ start(c) { c.enqueue(new Uint8Array([111, 107])); c.close(); } }));
  eq(await fromStream.text(), "ok", "a ReadableStream body");
  const used = new Response("x");
  await used.text();
  throws(() => used.clone(), "TypeError", "clone of a used body");
  const cl = new Response("twice");
  const cl2 = cl.clone();
  eq(await cl.text() + await cl2.text(), "twicetwice", "clone");
});

test("FormData", async () => {
  const f = new FormData();
  f.append("a", "1");
  f.append("a", "2");
  f.append("file", new Blob(["data"], { type: "text/x" }), "f.txt");
  eq(f.get("a"), "1", "get");
  eq(show(f.getAll("a")), '["1","2"]', "getAll");
  const file = f.get("file");
  ok(file instanceof File, "a file entry is a File");
  eq(file.name, "f.txt", "its name");
  eq(file.type, "text/x", "its type");
  eq(await file.text(), "data", "its bytes");
  f.set("a", "3");
  eq(show(f.getAll("a")), '["3"]', "set");
  eq([...f.keys()].join(), "a,file", "iteration");
  f.delete("file");
  eq(f.has("file"), false, "delete");
  eq(new FormData().get("x"), null, "get absent");
  f.append("blob", new Blob(["b"]));
  eq(f.get("blob").name, "blob", "a Blob without a name is named blob");
  const body = new Response(f);
  const ct = body.headers.get("content-type");
  ok(ct.startsWith("multipart/form-data; boundary="), "a multipart body");
  const back = await body.formData();
  eq(back.get("a"), "3", "multipart round trip (field)");
  eq(await back.get("blob").text(), "b", "multipart round trip (file)");
  const ue = await new Response("x=1&y=%20", { headers: { "content-type": "application/x-www-form-urlencoded" } }).formData();
  eq(ue.get("y"), " ", "urlencoded formData()");
  await rejects(new Response("x").formData(), "TypeError", "formData() of text/plain");
});

